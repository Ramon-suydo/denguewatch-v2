import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {verifyProtectedArtifacts,type ProtectedFingerprint} from './lib/protected-artifacts.ts';
import {buildLive,completeWeeks,validateLiveRows,type LiveData,type HistoricalWeek} from '../src/live-manila/model.ts';
const read=(path:string)=>JSON.parse(readFileSync(path,'utf8'));
const saved=read('data/processed/manila_live_weekly.json') as LiveData;
const history=read('data/processed/manila_weekly.json').scenarios.M as HistoricalWeek[];
const rows=validateLiveRows(saved.rows,read('data/live-manila/legacy-manifest.json').weeks);
const generated=buildLive(rows,history);
assert.deepEqual(saved.method,generated.method);assert.deepEqual(saved.metadata,generated.metadata);
const reviewed=read('data/live-manila/reviewed-2026.json').data as LiveData;
assert.ok(saved.rows.length>=reviewed.rows.length,'Reviewed weeks cannot be removed.');
assert.deepEqual(saved.rows.slice(0,reviewed.rows.length),reviewed.rows,'Reviewed corrections must be preserved; append new weeks or explicitly review another correction.');
assert.deepEqual(reviewed.method,buildLive(reviewed.rows,history).method);
const publicData=read('public/live-manila/weekly.json');
assert.deepEqual(publicData,{...saved,rows:saved.rows.map(({evidence_file:_private,...row})=>row)});
assert.deepEqual(read('public/live-manila/reference.json'),history);
const literal=(value:unknown)=>"'"+JSON.stringify(value).replaceAll("'","''")+"'::jsonb";
const expected='update private.manila_live_seed set rows='+literal(reviewed.rows)+',payload='+literal(reviewed)+',complete_counts='+literal(completeWeeks(history).map(r=>r.cases))+';';
const sql=readFileSync('supabase/migrations/20261106000100_manila_reviewed_corrections.sql','utf8');
assert.equal(sql.split(/\r?\n/).find(line=>line.startsWith('update private.manila_live_seed set rows=')),expected,'Forward correction seed must match the reviewed snapshot.');
const protectedFiles=read('data/live-manila/protected-canonical.json').files as Record<string,ProtectedFingerprint>;
const unchanged=verifyProtectedArtifacts(protectedFiles);
console.log(JSON.stringify({passed:true,rows:rows.length,protected_artifacts_unchanged:unchanged,ranges:generated.method.ranges}));
