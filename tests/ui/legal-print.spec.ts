import { test, expect } from "@playwright/test";
import AxeBuilder from "@axe-core/playwright";
import { readFile } from "node:fs/promises";
const snapshot = JSON.parse(await readFile("public/demo-snapshot.json", "utf8"));
const cache = snapshot.weekly;
test("draft legal sections, dormant consent, no app storage and offline A4 report", async ({ page, context }) => {
  const errors: string[] = [];
  page.on("pageerror", e => errors.push(e.message));
  page.on("console", m => { if (["error", "warning"].includes(m.type())) errors.push(m.text()); });
  await page.addInitScript(() => { Object.defineProperty(navigator, "onLine", { get: () => false }); window.print = () => { document.documentElement.dataset.printRequested = "true"; }; });
  await context.route("**/*", route => ["127.0.0.1", "localhost"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort());
  await page.goto("/legal");
  await expect(page.getByRole("heading", { name: "Legal and privacy notices" })).toBeVisible();
  await expect(page.getByText(/Version legal-v1/)).toHaveCount(6);
  for (const title of ["Privacy Notice", "Terms of Use", "Forecast & Medical Disclaimer", "Data Sources & Attribution", "Model Transparency", "Cookie/Storage Notice"]) await expect(page.getByRole("heading", { name: title, exact: true })).toBeVisible();
  await expect(page.getByText(/Controller\/DPO contact: \[pending\]/)).toBeVisible();
  expect((await new AxeBuilder({ page }).withTags(["wcag2a", "wcag2aa", "wcag21aa"]).analyze()).violations).toEqual([]);
  await page.getByRole("link", { name: "Open the existing model transparency panel" }).click();
  await expect(page.getByRole("heading", { name: "Model transparency", exact: true })).toBeInViewport();
  await page.goto("/report");
  await expect(page.getByRole("checkbox")).not.toBeChecked();
  await expect(page.locator("[data-consent-version='community-v1']")).toBeVisible();
  await page.getByRole("checkbox").check();
  await expect(page.getByRole("button", { name: "Continue to report" })).toBeDisabled();
  const city = snapshot.cities.find((c: { name: string }) => c.name === "MANILA CITY");
  await page.goto("/city/" + city.id);
  const button = page.getByRole("button", { name: "Print report", exact: true });
  await expect(button).toBeEnabled();
  await button.click();
  await expect(page.locator("html")).toHaveAttribute("data-print-requested", "true");
  await context.setOffline(true);
  await page.emulateMedia({ media: "print" });
  const report = page.getByRole("article", { name: "LGU print report" });
  await expect(report).toBeVisible();
  await expect(report).toContainText("MANILA CITY");
  await expect(report).toContainText("not medical advice");
  await expect(report).toContainText("Demo snapshot captured");
  await expect(report).toContainText("4-week mean estimate");
  await expect(report).toContainText("[exact citation pending]");
  const score = cache.summary.find((s: { city: string; horizon: number; model: string; cohort: string }) => s.city === city.name && s.horizon === 1 && s.model === cache.selected && s.cohort === "all-2019-onward");
  await expect(report).toContainText(score.mae.toFixed(2));
  await expect(page.getByRole("banner")).toBeHidden();
  await expect(button).toBeHidden();
  const pdf = await page.pdf({ format: "A4", preferCSSPageSize: true });
  expect(pdf.length).toBeGreaterThan(10000);
  expect(await page.evaluate(() => ({ local: localStorage.length, session: sessionStorage.length, cookie: document.cookie }))).toEqual({ local: 0, session: 0, cookie: "" });
  expect(errors).toEqual([]);
});
